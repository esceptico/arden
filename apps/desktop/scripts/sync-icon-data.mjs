import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import * as Hugeicons from "@hugeicons/core-free-icons";

const componentPath = fileURLToPath(new URL("../src/components/icons.tsx", import.meta.url));
const outputPath = fileURLToPath(new URL("../src/components/iconData.ts", import.meta.url));
const packageIconUrl = new URL("../node_modules/@hugeicons/core-free-icons/dist/esm/", import.meta.url);
const source = readFileSync(componentPath, "utf8");
const requested = [
  ...source.matchAll(/defineIcon\(Hugeicons\.([A-Za-z0-9]+)/g),
].map((match) => match[1]);

const exports = [...new Set(requested)]
  .sort()
  .map((name) => {
    const icon = Hugeicons[name];
    if (!icon) throw new Error(`Unknown Hugeicon export: ${name}`);

    const candidates = Object.keys(Hugeicons).filter((candidate) =>
      candidate.endsWith("Icon") &&
      Hugeicons[candidate] === icon &&
      existsSync(fileURLToPath(new URL(`${candidate}.js`, packageIconUrl))),
    );
    const file =
      candidates.find((candidate) => candidate === name) ??
      candidates.find((candidate) => !/[0-9]Icon$/.test(candidate)) ??
      candidates[0];
    if (!file) throw new Error(`No individual Hugeicon file found for: ${name}`);

    return `export { default as ${name} } from "@hugeicons/core-free-icons/${file}";`;
  });

writeFileSync(
  outputPath,
  `// Generated by scripts/sync-icon-data.mjs. Do not hand-edit.\n${exports.join("\n")}\n`,
);
